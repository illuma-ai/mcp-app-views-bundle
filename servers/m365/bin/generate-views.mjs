#!/usr/bin/env node
/**
 * Bundles the browser code of the interactive views (src/views/client + kit + mail) together with
 * the MCP Apps SDK into one minified script and writes it to src/generated/views-bundle.ts, where
 * the server embeds it into each self-contained view document. Invoked by `npm run generate`.
 */
import { mkdirSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { build } from 'esbuild';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(rootDir, 'src', 'generated', 'views-bundle.ts');

const result = await build({
  entryPoints: [path.join(rootDir, 'src', 'views', 'client', 'main.tsx')],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  target: 'es2020',
  platform: 'browser',
  legalComments: 'none',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
});

// The script is inlined in a <script> element: neutralise sequences the HTML parser would act on.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\/script').replace(/<!--/g, '<\!--');

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by bin/generate-views.mjs. Do not edit.\nexport const VIEW_BUNDLE_JS = ${JSON.stringify(js)};\n`
);
console.log(
  `views bundle: ${(js.length / 1024).toFixed(0)} KB -> ${path.relative(rootDir, outFile)}`
);
